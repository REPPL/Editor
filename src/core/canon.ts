/**
 * The canon's placement table: what each construct does in each rendering.
 *
 * `05-internals.md` section 3 writes it as a table with three columns —
 * Article, Slides, PDF — and this module is that table as data, one row per
 * construct, quoting the brief's own words for every cell. The table, not each
 * renderer, is where a placement lives: a renderer that decided for itself
 * would be a second copy of the rule, and two copies drift.
 *
 * Reading a row is how a renderer asks "what do I do with this?". Wording is
 * kept beside the placement so a test can hold the table against the brief,
 * and so a reader of the code sees what the brief actually says.
 */

import { hasClass, type Block, type Inline } from "./tree";

/** The three renderings phase 1 to phase 6 produce. */
export type Rendering = "article" | "slides" | "print";

/** Where a construct goes in a rendering. */
export type Placement =
  /** Into the contents list and the body as a heading. */
  | "contents"
  /** Into the deck through the slide mapping. */
  | "slide-mapping"
  /** Removed before rendering, with everything inside it. */
  | "filtered"
  /** Into the flow of the text as itself. */
  | "flow"
  /** Splits the slide in force. */
  | "split"
  /** A slide whose face is the headline alone. */
  | "section-break"
  /** An appendix of sources at the end. */
  | "appendix"
  /** A slide listing the sources. */
  | "slide-of-sources"
  /** Side-by-side columns. */
  | "columns"
  /** The slide's speaker notes. */
  | "notes"
  /** Not rendered at all. */
  | "absent"
  /** A callout box. */
  | "callout"
  /** A boxed aside in the printed page. */
  | "boxed-aside"
  /** A line at the foot of the slide. */
  | "foot"
  /** A note in the margin. */
  | "margin"
  /** A note, where the rendering puts its notes. */
  | "note"
  /** A player, falling back to the poster and a link. */
  | "player"
  /** The poster and a link, printed. */
  | "poster-link"
  /** A modal, once per browser. */
  | "modal"
  /** An epigraph on the first page. */
  | "epigraph"
  /** Collectable, revealed by the Konami code. */
  | "collectable"
  /** A static aside. */
  | "aside"
  /** Read and then thrown away: no output at all. */
  | "ignored"
  /** A page break. */
  | "page-break"
  /** A numbered entry in the reference list. */
  | "numbered-reference"
  /** Generated by the renderer rather than written by the author. */
  | "generated"
  /** Honoured as written. */
  | "honoured";

/** One cell: what happens, and the brief's own words for it. */
export interface CanonCell {
  readonly placement: Placement;
  /** Quoted from `05-internals.md` section 3. */
  readonly wording: string;
}

/** One row of the placement table. */
export interface CanonRow {
  /** A stable id, used by a renderer that has no block to match. */
  readonly id: string;
  /** The construct's name, as section 3 writes it. */
  readonly construct: string;
  readonly article: CanonCell;
  readonly slides: CanonCell;
  readonly print: CanonCell;
  /**
   * The phase the construct is seeded in — the phase from which an author may
   * write it and every rendering knows what to do with it, even when what one
   * of them does is ignore it. `06-delivery.md` sets these.
   */
  readonly phase: number;
  /** Whether a block is this construct. */
  readonly matches?: (block: Block) => boolean;
  /** Whether an inline node is this construct. */
  readonly matchesInline?: (inline: Inline) => boolean;
}

