/** One row by id. */
export function rowById(id: string): CanonRow | undefined {
  return CANON_ROWS.find((row) => row.id === id);
}

/**
 * The row a block belongs to, or undefined when the canon names no construct
 * for it.
 *
 * The table is read in order and the first match wins, so `## Interlude
 * {.divider}` is a divider rather than a heading: the more particular row is
 * written above the general one, as section 3 writes them.
 */
export function rowFor(block: Block): CanonRow | undefined {
  const rows = CANON_ROWS.filter((row) => row.matches?.(block) === true);
  return rows.find((row) => row.id !== "headings") ?? rows[0];
}

/** The row an inline node belongs to, if any. */
export function rowForInline(inline: Inline): CanonRow | undefined {
  return CANON_ROWS.find((row) => row.matchesInline?.(inline) === true);
}

/** Where a block goes in one rendering. */
export function placementOf(
  block: Block,
  rendering: Rendering,
): Placement | undefined {
  return rowFor(block)?.[rendering].placement;
}

/** Where an inline node goes in one rendering. */
export function inlinePlacementOf(
  inline: Inline,
  rendering: Rendering,
): Placement | undefined {
  return rowForInline(inline)?.[rendering].placement;
}
